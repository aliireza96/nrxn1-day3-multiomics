build_nrxn1_isoform_plot <- function(tx_df) {
  alpha_ids <- c("ENST00000675235", "ENST00000628515", "ENST00000404971", "ENST00000626249")
  beta_ids <- c("ENST00000342183", "ENST00000628364", "ENST00000401669")
  nrxn1_df <- tx_df[tx_df$gene_name == "NRXN1", , drop = FALSE]
  if (!nrow(nrxn1_df)) stop("No NRXN1 transcripts found in transcript results table.")
  nrxn1_df$baseMean <- as.numeric(nrxn1_df$baseMean)
  nrxn1_df$log2FoldChange <- as.numeric(nrxn1_df$log2FoldChange)
  nrxn1_df$padj <- as.numeric(nrxn1_df$padj)
  nrxn1_df$isoform_class <- "Other / unclassified"
  nrxn1_df$isoform_class[nrxn1_df$transcript_id %in% alpha_ids] <- "Alpha isoforms"
  nrxn1_df$isoform_class[nrxn1_df$transcript_id %in% beta_ids] <- "Beta isoforms"
  nrxn1_df$isoform_class <- factor(nrxn1_df$isoform_class, levels = c("Alpha isoforms", "Beta isoforms", "Other / unclassified"))
  nrxn1_df$significant <- factor(
    ifelse(!is.na(nrxn1_df$padj) & nrxn1_df$padj < 0.05, "Significant", "Not significant"),
    levels = c("Significant", "Not significant")
  )
  plot_df <- nrxn1_df[nrxn1_df$isoform_class != "Other / unclassified", , drop = FALSE]
  plot_df <- plot_df[order(plot_df$isoform_class, plot_df$log2FoldChange, decreasing = TRUE), , drop = FALSE]
  plot_df$transcript_id <- factor(plot_df$transcript_id, levels = rev(unique(plot_df$transcript_id)))
  class_colors <- c("Alpha isoforms" = "steelblue", "Beta isoforms" = "tomato", "Other / unclassified" = "grey60")
  x_lim <- range(c(plot_df$log2FoldChange, 0), na.rm = TRUE)
  x_pad <- max(1, diff(x_lim) * 0.14)

  p <- ggplot2::ggplot(plot_df, ggplot2::aes(x = log2FoldChange, y = transcript_id, color = isoform_class)) +
    ggplot2::geom_segment(ggplot2::aes(x = 0, xend = log2FoldChange, yend = transcript_id), linewidth = 1.1, alpha = 0.95, lineend = "round") +
    ggplot2::geom_point(ggplot2::aes(shape = significant), size = 4.3, stroke = 1.1, fill = "white") +
    ggplot2::geom_vline(xintercept = 0, linetype = "dashed", color = "grey55", linewidth = 0.4) +
    ggplot2::facet_grid(isoform_class ~ ., scales = "free_y", space = "free_y", switch = "y") +
    ggplot2::scale_color_manual(values = class_colors, guide = "none") +
    ggplot2::scale_shape_manual(values = c("Significant" = 16, "Not significant" = 1), name = NULL) +
    ggplot2::coord_cartesian(xlim = c(x_lim[1] - x_pad * 0.35, x_lim[2] + x_pad * 1.45), clip = "off") +
    ggplot2::labs(
      title = "NRXN1 isoform expression",
      x = "log2 Fold Change (patient vs. control)",
      y = NULL
    ) +
    theme_manuscript(base_size = 10.5) +
    ggplot2::theme(
      strip.placement = "outside",
      strip.background = ggplot2::element_rect(fill = "grey95", color = NA),
      strip.text.y.left = ggplot2::element_text(angle = 0, face = "bold", size = 9),
      axis.text.y = ggplot2::element_text(size = 8.1, family = "mono"),
      axis.text.x = ggplot2::element_text(size = 8.5),
      legend.position = "bottom",
      legend.box = "horizontal",
      legend.title = ggplot2::element_blank(),
      legend.text = ggplot2::element_text(size = 8.1),
      panel.grid.major.y = ggplot2::element_blank(),
      plot.margin = ggplot2::margin(t = 8, r = 18, b = 8, l = 8),
      plot.title = ggplot2::element_text(size = 12.5, face = "bold"),
      plot.subtitle = ggplot2::element_blank(),
      plot.caption = ggplot2::element_blank()
    )
  p
}

