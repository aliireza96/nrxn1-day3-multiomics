select_terms_strict <- function(df, terms, label) {
  sel <- df[df$Description %in% terms, , drop = FALSE]
  missing_terms <- setdiff(terms, unique(sel$Description))
  if (length(missing_terms)) {
    stop("Missing required terms for ", label, ": ", paste(missing_terms, collapse = ", "))
  }
  sel
}

format_padj_label <- function(x) {
  paste0("padj=", format(as.numeric(x), scientific = TRUE, digits = 2))
}

parse_ratio_string <- function(x) {
  vapply(
    strsplit(as.character(x), "/", fixed = TRUE),
    function(parts) {
      if (length(parts) != 2L) return(NA_real_)
      num <- suppressWarnings(as.numeric(parts[[1]]))
      den <- suppressWarnings(as.numeric(parts[[2]]))
      if (!is.finite(num) || !is.finite(den) || den == 0) return(NA_real_)
      num / den
    },
    numeric(1)
  )
}

build_go_minimal_plot <- function(
  df,
  title_text,
  score_col,
  count_col,
  term_col,
  x_label = "Enrichment score",
  x_max = NULL,
  fill_color = "#8fb7df",
  point_color = "#084594"
) {
  if (is.null(df) || !nrow(df)) return(NULL)
  plot_df <- df
  plot_df$score <- as.numeric(plot_df[[score_col]])
  plot_df$count_n <- as.numeric(plot_df[[count_col]])
  plot_df$term_label <- as.character(plot_df[[term_col]])
  plot_df <- plot_df[is.finite(plot_df$score) & is.finite(plot_df$count_n), , drop = FALSE]
  if (!nrow(plot_df)) return(NULL)

  plot_df <- plot_df[order(plot_df$score, plot_df$count_n, decreasing = TRUE), , drop = FALSE]
  plot_df$count_label <- format(plot_df$count_n, big.mark = ",", trim = TRUE)
  plot_df$term_label <- factor(plot_df$term_label, levels = rev(unique(plot_df$term_label)))
  x_upper <- if (!is.null(x_max) && is.finite(x_max)) x_max else max(plot_df$score, na.rm = TRUE)
  label_offset <- x_upper * 0.045

  ggplot2::ggplot(plot_df, ggplot2::aes(x = score, y = term_label)) +
    ggplot2::geom_segment(
      ggplot2::aes(x = 0, xend = score, yend = term_label),
      linewidth = 1.5,
      color = fill_color,
      lineend = "round"
    ) +
    ggplot2::geom_point(size = 3.1, shape = 21, stroke = 0.3, fill = point_color, color = point_color) +
    ggplot2::geom_label(
      ggplot2::aes(x = score + label_offset, label = count_label),
      hjust = 0,
      size = 2.9,
      label.size = 0.12,
      label.padding = grid::unit(0.08, "lines"),
      fill = grDevices::adjustcolor("white", alpha.f = 0.92),
      color = "#2c3e50"
    ) +
    ggplot2::scale_x_continuous(
      limits = c(0, x_upper * 1.22),
      expand = ggplot2::expansion(mult = c(0, 0))
    ) +
    ggplot2::labs(title = title_text, x = x_label, y = NULL) +
    theme_manuscript(base_size = 11) +
    ggplot2::coord_cartesian(clip = "off") +
    ggplot2::theme(
      axis.text.y = ggplot2::element_text(size = 8.8, lineheight = 0.9, margin = ggplot2::margin(r = 4)),
      plot.margin = ggplot2::margin(t = 7, r = 18, b = 7, l = 7)
    )
}

build_go_directional_lollipop <- function(
  up_df,
  down_df,
  title_text,
  score_col = "enrichment_score",
  count_col = "Count",
  term_col = "Description_wrapped",
  x_label = expression(-log[10]("adjusted p")),
  up_color = "#d1495b",
  down_color = "#2f6bff"
) {
  if (is.null(up_df) || !nrow(up_df) || is.null(down_df) || !nrow(down_df)) return(NULL)
  up_plot <- up_df
  down_plot <- down_df
  up_plot$direction <- "Increased"
  down_plot$direction <- "Decreased"
  plot_df <- rbind(up_plot, down_plot)
  plot_df$score <- as.numeric(plot_df[[score_col]])
  plot_df$count_n <- as.numeric(plot_df[[count_col]])
  plot_df$term_label <- as.character(plot_df[[term_col]])
  plot_df <- plot_df[is.finite(plot_df$score) & is.finite(plot_df$count_n), , drop = FALSE]
  if (!nrow(plot_df)) return(NULL)

  plot_df$signed_score <- ifelse(plot_df$direction == "Increased", plot_df$score, -plot_df$score)
  plot_df$count_label <- format(plot_df$count_n, big.mark = ",", trim = TRUE)
  plot_df <- plot_df[order(plot_df$signed_score, decreasing = TRUE), , drop = FALSE]
  plot_df$term_label <- factor(plot_df$term_label, levels = rev(unique(plot_df$term_label)))
  max_abs <- max(abs(plot_df$signed_score), na.rm = TRUE)
  label_offset <- max_abs * 0.05

  ggplot2::ggplot(plot_df, ggplot2::aes(x = signed_score, y = term_label, color = direction)) +
    ggplot2::geom_vline(xintercept = 0, color = "grey82", linewidth = 0.4) +
    ggplot2::geom_segment(
      ggplot2::aes(x = 0, xend = signed_score, yend = term_label),
      linewidth = 1.4,
      lineend = "round",
      alpha = 0.92
    ) +
    ggplot2::geom_point(size = 3.0) +
    ggplot2::geom_label(
      ggplot2::aes(
        x = ifelse(direction == "Increased", signed_score + label_offset, signed_score - label_offset),
        label = count_label
      ),
      hjust = ifelse(plot_df$direction == "Increased", 0, 1),
      size = 2.8,
      label.size = 0.12,
      label.padding = grid::unit(0.08, "lines"),
      fill = grDevices::adjustcolor("white", alpha.f = 0.92),
      color = "#2c3e50"
    ) +
    ggplot2::scale_color_manual(values = c("Increased" = up_color, "Decreased" = down_color), name = NULL) +
    ggplot2::scale_x_continuous(
      limits = c(-max_abs * 1.24, max_abs * 1.24),
      expand = ggplot2::expansion(mult = c(0, 0)),
      labels = function(x) format(abs(x), trim = TRUE)
    ) +
    ggplot2::labs(title = title_text, x = x_label, y = NULL) +
    theme_manuscript(base_size = 11) +
    ggplot2::coord_cartesian(clip = "off") +
    ggplot2::theme(
      axis.text.y = ggplot2::element_text(size = 8.6, lineheight = 0.88, margin = ggplot2::margin(r = 4)),
      plot.margin = ggplot2::margin(t = 7, r = 18, b = 7, l = 18),
      legend.position = "top"
    )
}

