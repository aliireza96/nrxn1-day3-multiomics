write_rna_heatmaps <- function(
  vsd,
  sig_genes,
  output_top_path = NULL,
  output_all_path,
  title_prefix = "RNA-seq",
  top_cellwidth = 14,
  top_cellheight = 8,
  all_cellwidth = 20,
  all_cellheight = 0.15,
  all_gene_panel_n = Inf
) {
  if (!requireNamespace("pheatmap", quietly = TRUE)) {
    message("pheatmap unavailable; skipping RNA heatmaps.")
    return(invisible(NULL))
  }

  assay_mat <- SummarizedExperiment::assay(vsd)
  sig_genes$padj <- as.numeric(sig_genes$padj)
  col_annot <- NULL
  if ("genotype_group" %in% colnames(SummarizedExperiment::colData(vsd))) {
    col_annot <- data.frame(
      condition = SummarizedExperiment::colData(vsd)$genotype_group,
      row.names = colnames(assay_mat),
      stringsAsFactors = FALSE
    )
  }
  annot_colors <- list(condition = c(control = "#2f6bff", patient = "#d1495b"))
  if (!is.null(col_annot)) {
    col_annot$condition <- factor(col_annot$condition, levels = c("control", "patient"))
    column_order <- order(col_annot$condition, rownames(col_annot))
    assay_mat <- assay_mat[, column_order, drop = FALSE]
    col_annot <- col_annot[column_order, , drop = FALSE]
  }
  top_genes <- unique(sig_genes$gene_name[order(sig_genes$padj)])
  top_genes <- top_genes[top_genes %in% rownames(assay_mat)]
  top_genes <- top_genes[seq_len(min(50, length(top_genes)))]

  if (!is.null(output_top_path) && length(top_genes) > 1) {
    mat_top <- assay_mat[top_genes, , drop = FALSE]
    mat_top_scaled <- t(scale(t(mat_top)))
    mat_top_scaled <- mat_top_scaled[stats::complete.cases(mat_top_scaled), , drop = FALSE]
    grDevices::pdf(output_top_path, width = 6, height = 8)
    pheatmap::pheatmap(
      mat_top_scaled,
      cluster_rows = TRUE,
      cluster_cols = TRUE,
      treeheight_row = 0,
      treeheight_col = 0,
      show_rownames = TRUE,
      show_colnames = TRUE,
      annotation_col = col_annot,
      annotation_colors = annot_colors,
      fontsize_row = 7,
      cellwidth = top_cellwidth,
      cellheight = top_cellheight,
      main = paste0(title_prefix, ": top 50 DEGs (z-scored VST)"),
      color = colorRampPalette(c("#2f6bff", "white", "#d1495b"))(50),
      border_color = NA
    )
    grDevices::dev.off()
    message("  Saved: ", basename(output_top_path))
  }

  gene_variances <- apply(assay_mat, 1, stats::var, na.rm = TRUE)
  gene_variances <- sort(gene_variances[is.finite(gene_variances)], decreasing = TRUE)
  if (is.infinite(all_gene_panel_n)) {
    all_gene_panel_n <- min(500, length(gene_variances))
  }
  keep_all_genes <- names(gene_variances)[seq_len(min(all_gene_panel_n, length(gene_variances)))]
  mat_all <- assay_mat[keep_all_genes, , drop = FALSE]
  mat_all_scaled <- t(scale(t(mat_all)))
  mat_all_scaled <- mat_all_scaled[stats::complete.cases(mat_all_scaled), , drop = FALSE]
  if (nrow(mat_all_scaled) > 1) {
    padded_col_labels <- paste0(" ", colnames(mat_all_scaled), " ")
    draw_all_heatmap <- function() {
      hm <- pheatmap::pheatmap(
        mat_all_scaled,
        cluster_rows = TRUE,
        cluster_cols = TRUE,
        treeheight_row = 0,
        treeheight_col = 0,
        show_rownames = FALSE,
        show_colnames = TRUE,
        labels_col = padded_col_labels,
        annotation_col = col_annot,
        annotation_colors = annot_colors,
        fontsize_col = 8,
        angle_col = 45,
        main = paste0(title_prefix, ": top variable genes"),
        color = colorRampPalette(c("#2f6bff", "white", "#d1495b"))(101),
        breaks = seq(-3, 3, length.out = 102),
        border_color = NA,
        silent = TRUE
      )
      grid::grid.newpage()
      grid::pushViewport(grid::viewport(x = 0.535, y = 0.525, width = 0.93, height = 0.93))
      grid::grid.draw(hm$gtable)
      grid::upViewport()
    }
    grDevices::pdf(output_all_path, width = 9.2, height = 9.6)
    draw_all_heatmap()
    grDevices::dev.off()
    message("  Saved: ", basename(output_all_path))
  }
}

apply_tobias_quantile_threshold <- function(df, pos_quantile = 0.95, neg_p_quantile = pos_quantile, neg_change_quantile = 1 - pos_quantile) {
  df$plot_change <- as.numeric(df$plot_change)
  df$p_value <- as.numeric(df$p_value)
  df$neg_log10_p <- as.numeric(df$neg_log10_p)

  p_cut_pos <- stats::quantile(df$neg_log10_p, probs = pos_quantile, na.rm = TRUE)
  p_cut_neg <- stats::quantile(df$neg_log10_p, probs = neg_p_quantile, na.rm = TRUE)
  fc_cut_pos <- stats::quantile(df$plot_change, probs = pos_quantile, na.rm = TRUE)
  fc_cut_neg <- stats::quantile(df$plot_change, probs = neg_change_quantile, na.rm = TRUE)

  df$sig_status <- ifelse(
    ((df$neg_log10_p > p_cut_pos & df$plot_change > 0) | (df$plot_change > fc_cut_pos & df$plot_change > 0)),
    "More accessible in patient",
    ifelse(
      ((df$neg_log10_p > p_cut_neg & df$plot_change < 0) | (df$plot_change < fc_cut_neg & df$plot_change < 0)),
      "Less accessible in patient",
      "NS"
    )
  )
  df
}

