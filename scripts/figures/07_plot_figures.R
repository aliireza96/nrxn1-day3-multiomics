build_rna_chip_concordance_violin <- function(df) {
  plot_df <- df
  total_n <- nrow(plot_df)
  plot_df$rna_log2fc <- as.numeric(plot_df$rna_log2fc)
  plot_df$chip_log2fc <- as.numeric(plot_df$chip_log2fc)
  plot_df <- plot_df[
    (plot_df$chip_log2fc > 0 & plot_df$rna_log2fc < 0) |
      (plot_df$chip_log2fc < 0 & plot_df$rna_log2fc > 0),
    ,
    drop = FALSE
  ]
  concordant_n <- nrow(plot_df)
  concordant_pct <- if (total_n > 0) 100 * concordant_n / total_n else NA_real_
  plot_df$chip_group <- ifelse(plot_df$chip_log2fc > 0, "Gained H3K27me3", "Lost H3K27me3")
  plot_df$chip_group <- factor(plot_df$chip_group, levels = c("Lost H3K27me3", "Gained H3K27me3"))
  counts <- table(plot_df$chip_group)
  y_min <- min(plot_df$rna_log2fc, na.rm = TRUE)
  y_max <- max(plot_df$rna_log2fc, na.rm = TRUE)
  y_span <- y_max - y_min
  p <- ggplot2::ggplot(plot_df, ggplot2::aes(x = chip_group, y = rna_log2fc, fill = chip_group, color = chip_group)) +
    ggplot2::geom_point(
      position = ggplot2::position_jitter(width = 0.055, height = 0),
      size = 0.7,
      alpha = 0.26,
      shape = 16,
      stroke = 0,
      show.legend = FALSE
    ) +
    ggplot2::geom_violin(trim = FALSE, width = 0.56, scale = "width", alpha = 0.46, color = NA) +
    ggplot2::geom_boxplot(width = 0.16, outlier.shape = NA, alpha = 0.9) +
    ggplot2::geom_hline(yintercept = 0, linetype = "dashed", color = "grey55", linewidth = 0.4) +
    ggplot2::scale_fill_manual(
      values = c("Lost H3K27me3" = "#2f6bff", "Gained H3K27me3" = "#d1495b"),
      name = NULL
    ) +
    ggplot2::scale_color_manual(
      values = c("Lost H3K27me3" = "#2f6bff", "Gained H3K27me3" = "#d1495b"),
      name = NULL
    ) +
    ggplot2::labs(
      title = NULL,
      subtitle = NULL,
      x = NULL,
      y = "RNA log2FC (patient vs control)"
    ) +
    theme_manuscript(base_size = 12) +
    ggplot2::scale_x_discrete(expand = ggplot2::expansion(add = 0.18)) +
    ggplot2::coord_cartesian(clip = "off") +
    ggplot2::theme(
      legend.position = "none",
      panel.grid.major.y = ggplot2::element_line(color = "grey92", linewidth = 0.30),
      plot.margin = ggplot2::margin(7, 8, 14, 6)
    )
  p +
    ggplot2::annotate(
      "text",
      x = 1.5,
      y = y_max + 0.08 * y_span,
      label = paste0("Concordant: ", concordant_n, "/", total_n, " (", sprintf("%.1f", concordant_pct), "%)"),
      size = 3.3,
      color = "#444"
    ) +
    ggplot2::annotate(
      "text",
      x = c(1, 2),
      y = y_min - 0.10 * y_span,
      label = c(paste0("n=", counts[[1]]), paste0("n=", counts[[2]])),
      size = 3.2
    )
}

build_rna_chip_scatter_v2 <- function(df) {
  plot_df <- df
  plot_df$chip_group <- ifelse(plot_df$chip_log2fc > 0, "H3K27me3 gained", "H3K27me3 lost")
  cor_res <- stats::cor.test(plot_df$rna_log2fc, plot_df$chip_log2fc, method = "pearson")
  ggplot2::ggplot(plot_df, ggplot2::aes(x = chip_log2fc, y = rna_log2fc, color = chip_group)) +
    ggplot2::geom_point(size = 1.7, alpha = 0.8) +
    ggplot2::geom_smooth(method = "lm", se = TRUE, linewidth = 0.7, color = "#2c3e50") +
    ggplot2::geom_hline(yintercept = 0, linetype = "dashed", color = "grey70", linewidth = 0.35) +
    ggplot2::geom_vline(xintercept = 0, linetype = "dashed", color = "grey70", linewidth = 0.35) +
    ggplot2::scale_color_manual(values = c("H3K27me3 gained" = "#7f3c8d", "H3K27me3 lost" = "#f28e2b"), name = NULL) +
    ggplot2::labs(
      title = "RNA-H3K27me3 promoter overlap",
      subtitle = paste0("r=", round(unname(cor_res$estimate), 2), "; p=", format(cor_res$p.value, scientific = TRUE, digits = 2)),
      x = "H3K27me3 promoter log2FC (patient vs control)",
      y = "RNA log2FC (patient vs control)"
    ) +
    theme_manuscript(base_size = 10.5)
}

