build_rna_volcano_plot <- function(rna_res, lfc_threshold, title_text) {
  x_cap <- 15
  y_cap <- 50
  rna_res$log2FoldChange <- as.numeric(rna_res$log2FoldChange)
  rna_res$padj <- as.numeric(rna_res$padj)
  rna_res <- rna_res[is.finite(rna_res$log2FoldChange) & !is.na(rna_res$padj), ]
  rna_res$sig <- ifelse(
    rna_res$padj < 0.05 & abs(rna_res$log2FoldChange) >= lfc_threshold & rna_res$log2FoldChange > 0,
    "Up in patient",
    ifelse(
      rna_res$padj < 0.05 & abs(rna_res$log2FoldChange) >= lfc_threshold & rna_res$log2FoldChange < 0,
      "Down in patient",
      "NS"
    )
  )
  rna_res$neg_log10_padj <- -log10(pmax(rna_res$padj, .Machine$double.xmin))
  rna_res$x_clipped <- abs(rna_res$log2FoldChange) > x_cap
  rna_res$y_clipped <- rna_res$neg_log10_padj > y_cap
  rna_res$is_clipped <- rna_res$x_clipped | rna_res$y_clipped
  rna_res$plot_log2FoldChange <- pmax(pmin(rna_res$log2FoldChange, x_cap), -x_cap)
  rna_res$plot_neg_log10_padj <- pmin(rna_res$neg_log10_padj, y_cap)
  up_n <- sum(rna_res$sig == "Up in patient")
  down_n <- sum(rna_res$sig == "Down in patient")

  p <- ggplot2::ggplot(rna_res, ggplot2::aes(x = plot_log2FoldChange, y = plot_neg_log10_padj, color = sig)) +
    ggplot2::geom_point(
      data = rna_res[!rna_res$is_clipped, , drop = FALSE],
      size = 0.7,
      alpha = 0.7
    ) +
    ggplot2::geom_point(
      data = rna_res[rna_res$is_clipped, , drop = FALSE],
      shape = 17,
      size = 1.6,
      alpha = 0.85,
      show.legend = FALSE
    ) +
    ggplot2::geom_vline(xintercept = 0, color = "grey75", linewidth = 0.4) +
    ggplot2::geom_vline(xintercept = c(-lfc_threshold, lfc_threshold), color = "grey60", linewidth = 0.4, linetype = "dashed") +
    ggplot2::geom_hline(yintercept = y_cap, color = "grey82", linewidth = 0.35, linetype = "dotted") +
    ggplot2::scale_color_manual(
      values = c("Up in patient" = "#d1495b", "Down in patient" = "#2f6bff", "NS" = "#c7c7c7"),
      name = NULL
    ) +
    ggplot2::scale_x_continuous(
      limits = c(-x_cap, x_cap),
      breaks = c(-15, -10, -5, 0, 5, 10, 15),
      expand = ggplot2::expansion(mult = c(0.01, 0.01))
    ) +
    ggplot2::scale_y_continuous(
      limits = c(0, y_cap),
      breaks = c(0, 10, 20, 30, 40, 50),
      expand = ggplot2::expansion(mult = c(0, 0.01))
    ) +
    ggplot2::labs(
      title = title_text,
      subtitle = paste0(
        "DEGs: up = ", format(up_n, big.mark = ","), ", down = ", format(down_n, big.mark = ","),
        " (padj < 0.05, |log2FC| >= ", format(lfc_threshold, trim = TRUE), ")"
      ),
      x = "log2 fold change (patient / control)",
      y = "-log10(padj)",
      caption = "Axes clipped at |log2FC| = 15 and -log10(padj) = 50; edge triangles mark out-of-range genes."
    ) +
    theme_manuscript(base_size = 12) +
    ggplot2::theme(plot.caption = ggplot2::element_text(size = 8.5, color = "#666666"))

  list(
    plot = p,
    counts = data.frame(
      category = c("Up in patient", "Down in patient", "NS"),
      n = c(up_n, down_n, sum(rna_res$sig == "NS")),
      padj_threshold = 0.05,
      lfc_threshold = lfc_threshold,
      stringsAsFactors = FALSE
    ),
    annotated = rna_res
  )
}

