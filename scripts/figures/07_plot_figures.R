extract_go_plot_df <- function(ego, top_n = 10, wrap_width = 40) {
  if (is.null(ego)) return(NULL)
  df <- as.data.frame(ego@result)
  df$GeneRatio_num <- parse_ratio_string(df$GeneRatio)
  df$enrichment_score <- -log10(pmax(as.numeric(df$p.adjust), .Machine$double.xmin))
  df <- df[order(df$p.adjust, -df$GeneRatio_num, -df$Count), ][seq_len(min(top_n, nrow(df))), ]
  df$Description_wrapped <- wrap_text_vec(df$Description, width = wrap_width)
  df
}

