run_go <- function(gene_vec, label, output_path) {
  if (!requireNamespace("clusterProfiler", quietly = TRUE) || !requireNamespace("org.Hs.eg.db", quietly = TRUE)) {
    message("clusterProfiler/org.Hs.eg.db unavailable; skipping GO for: ", label); return(NULL)
  }
  ensure_dir(dirname(output_path))
  mapped <- tryCatch(
    clusterProfiler::bitr(unique(gene_vec), fromType = "SYMBOL", toType = "ENTREZID", OrgDb = org.Hs.eg.db::org.Hs.eg.db),
    error = function(e) NULL
  )
  if (is.null(mapped) || !nrow(mapped)) { message("No gene IDs mapped for: ", label); return(NULL) }
  ego <- tryCatch(
    clusterProfiler::enrichGO(gene = mapped$ENTREZID, OrgDb = org.Hs.eg.db::org.Hs.eg.db,
                               ont = "BP", pAdjustMethod = "BH", pvalueCutoff = 0.05, qvalueCutoff = 0.2),
    error = function(e) NULL
  )
  if (is.null(ego) || !nrow(ego@result)) { message("No GO terms enriched for: ", label); return(NULL) }
  ego_df <- as.data.frame(ego@result)
  ego_df$GeneRatio_num <- parse_ratio_string(ego_df$GeneRatio)
  ego_df$enrichment_score <- -log10(pmax(as.numeric(ego_df$p.adjust), .Machine$double.xmin))
  write.table(ego_df, output_path, sep = "\t", quote = FALSE, row.names = FALSE)
  ego
}

theme_manuscript <- function(base_size = 12) {
  ggplot2::theme_bw(base_size = base_size) +
    ggplot2::theme(
      panel.grid.major.y = ggplot2::element_blank(),
      panel.grid.minor = ggplot2::element_blank(),
      plot.title = ggplot2::element_text(face = "bold"),
      legend.title = ggplot2::element_text(face = "bold")
    )
}

